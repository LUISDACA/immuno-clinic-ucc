import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { AxiosError, type AxiosResponse } from 'axios';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { toast } from 'sonner';
import EvidencePage from '@/app/student/evidence/page';
import { listMyEvidence, uploadEvidence } from '@/lib/api/evidence';
import { getMyScheme } from '@/lib/api/scheme';
vi.mock('next/navigation', () => ({ useRouter: () => ({ push: vi.fn() }), useSearchParams: () => new URLSearchParams('page=2'), usePathname: () => '/student/evidence' }));
vi.mock('@/lib/api/evidence', () => ({ listMyEvidence: vi.fn(), uploadEvidence: vi.fn(), deleteEvidenceBatch: vi.fn(), downloadEvidenceFile: vi.fn() }));
vi.mock('@/lib/api/scheme', () => ({ getMyScheme: vi.fn() }));
vi.mock('sonner', () => ({ toast: { success: vi.fn(), warning: vi.fn(), error: vi.fn() } }));
const confirmed = 'Los documentos se subieron, pero no se pudo actualizar la lista.';
const failed = 'No se pudo confirmar la carga. Comprueba tus documentos antes de reintentar.';
const initial = { page: 2, page_size: 20, total: 21, total_pages: 2, has_next: false, has_previous: true, items: [{ id: 'synthetic-batch', status: 'in_review', created_at: '2026-01-01T10:00:00Z', notes: 'Synthetic previous data', files: [] }] };
const failure = (status: number) => new AxiosError('PRIVATE_DIAGNOSTIC', undefined, undefined, undefined, { status, data: { message: 'PRIVATE_DIAGNOSTIC' } } as AxiosResponse);
beforeEach(() => {
  vi.clearAllMocks();
  vi.mocked(listMyEvidence).mockResolvedValue(initial as never);
  vi.mocked(getMyScheme).mockResolvedValue({ vaccines: [] } as never);
  vi.mocked(uploadEvidence).mockResolvedValue({} as never);
});
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
async function mount() {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false }, mutations: { retry: false } } });
  const view = render(<QueryClientProvider client={client}><EvidencePage /></QueryClientProvider>);
  await screen.findByText('Synthetic previous data');
  const pdf = new File(['%PDF-synthetic'], 'synthetic.pdf', { type: 'application/pdf' });
  fireEvent.change(view.container.querySelector('input[type=file]')!, { target: { files: [pdf] } });
  fireEvent.change(screen.getByLabelText('Notas (opcional)'), { target: { value: 'Synthetic draft' } });
  return { client, pdf };
}
it.each([401,403,404,429,500,503])('confirmed POST + failed GET %s is recoverable with a single GET, never POST', async status => {
  await mount();
  vi.mocked(listMyEvidence).mockRejectedValue(failure(status));
  const submit = screen.getByRole('button', { name: 'Subir evidencia' });
  fireEvent.click(submit); fireEvent.click(submit);
  await screen.findByText(confirmed);
  expect(uploadEvidence).toHaveBeenCalledTimes(1);
  expect(toast.success).not.toHaveBeenCalledWith('Evidencia cargada');
  expect(toast.warning).toHaveBeenCalledWith(confirmed);
  expect(screen.queryByText('Synthetic previous data')).not.toBeInTheDocument();
  expect(screen.queryByText('Aún no has cargado evidencia')).not.toBeInTheDocument();
  expect(screen.queryByLabelText('Notas (opcional)')).not.toBeInTheDocument();
  expect(screen.queryByText('PRIVATE_DIAGNOSTIC')).not.toBeInTheDocument();
  let resolve!: (data: never) => void;
  vi.mocked(listMyEvidence).mockImplementation(() => new Promise(yes => { resolve = yes; }));
  const before = vi.mocked(listMyEvidence).mock.calls.length;
  const retry = screen.getByRole('button', { name: 'Reintentar' });
  fireEvent.click(retry); fireEvent.click(retry);
  await waitFor(() => expect(listMyEvidence).toHaveBeenCalledTimes(before+1));
  expect(retry).toBeDisabled();
  await act(async () => resolve(initial as never));
  await screen.findByText('Synthetic previous data');
  expect(uploadEvidence).toHaveBeenCalledTimes(1);
  expect(screen.getByLabelText('Notas (opcional)')).toHaveValue('');
  expect(screen.queryByText('synthetic.pdf')).not.toBeInTheDocument();
  expect(listMyEvidence).toHaveBeenLastCalledWith(2,20);
});
it('failed POST + failed GET preserves the draft and feedback; recovery GET never retries the write', async () => {
  const { pdf } = await mount();
  vi.mocked(listMyEvidence).mockRejectedValue(failure(403));
  vi.mocked(uploadEvidence).mockRejectedValue(failure(503));
  fireEvent.click(screen.getByRole('button', { name: 'Subir evidencia' }));
  await screen.findByText(failed);
  expect(screen.queryByText(confirmed)).not.toBeInTheDocument();
  vi.mocked(listMyEvidence).mockResolvedValue(initial as never);
  fireEvent.click(screen.getByRole('button', { name: 'Reintentar' }));
  await screen.findByText('Synthetic previous data');
  expect(screen.getByLabelText('Notas (opcional)')).toHaveValue('Synthetic draft');
  expect(screen.getByText('synthetic.pdf')).toBeInTheDocument();
  expect(screen.getByText(failed)).toBeInTheDocument();
  expect(uploadEvidence).toHaveBeenCalledTimes(1);
  vi.mocked(uploadEvidence).mockResolvedValue({} as never);
  fireEvent.click(screen.getByRole('button', { name: 'Subir evidencia' }));
  await waitFor(() => expect(uploadEvidence).toHaveBeenCalledTimes(2));
  expect(uploadEvidence).toHaveBeenLastCalledWith([pdf],'Synthetic draft',undefined);
  await waitFor(() => expect(screen.queryByText('synthetic.pdf')).not.toBeInTheDocument());
});
it('a later failure after a successful identical read cannot resurrect an old confirmed-upload notice', async () => {
  const { client } = await mount();
  vi.mocked(listMyEvidence).mockRejectedValue(failure(503));
  fireEvent.click(screen.getByRole('button', { name: 'Subir evidencia' }));
  await screen.findByText(confirmed);
  vi.mocked(listMyEvidence).mockResolvedValue(initial as never);
  fireEvent.click(screen.getByRole('button', { name: 'Reintentar' }));
  await screen.findByText('Synthetic previous data');
  vi.mocked(listMyEvidence).mockRejectedValue(failure(503));
  await act(async () => { await client.invalidateQueries({ queryKey: ['evidence','me',2] }); });
  expect(await screen.findByRole('button', { name: 'Reintentar' })).toBeEnabled();
  expect(screen.queryByText(confirmed)).not.toBeInTheDocument();
});
it('a pre-write read cannot replace the confirmed post-write list', async () => {
  const { client } = await mount();
  let obsolete!: (data: never) => void;
  vi.mocked(listMyEvidence).mockImplementationOnce(() => new Promise(yes => { obsolete = yes; }));
  void client.invalidateQueries({ queryKey: ['evidence','me',2] });
  await waitFor(() => expect(listMyEvidence).toHaveBeenCalledTimes(2));
  vi.mocked(listMyEvidence).mockResolvedValue({ ...initial, items: [{ ...initial.items[0], notes: 'Synthetic current data' }] } as never);
  fireEvent.click(screen.getByRole('button', { name: 'Subir evidencia' }));
  await screen.findByText('Synthetic current data');
  await act(async () => obsolete(initial as never));
  expect(screen.queryByText('Synthetic previous data')).not.toBeInTheDocument();
  expect(uploadEvidence).toHaveBeenCalledTimes(1);
});
